import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines,
  buildWindowsHookStdinDrainEpilogue
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%BBQ_AGENT_HOOK_PORT%"=="" if defined BBQ_AGENT_HOOK_ENDPOINT if exist "%BBQ_AGENT_HOOK_ENDPOINT%" call "%BBQ_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%BBQ_AGENT_HOOK_TOKEN%"=="" if not "%BBQ_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\orca-dev\\agent-hooks" for /r "%APPDATA%\\orca-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'if "%BBQ_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\orca\\agent-hooks" for /r "%APPDATA%\\orca\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%BBQ_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set BBQ_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%BBQ_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ...buildWindowsHookStdinDrainEpilogue(),
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__bbq_read_ancestor_var() {',
    '  __bbq_name="$1"',
    '  __bbq_pid="${PPID:-}"',
    '  while [ -n "$__bbq_pid" ] && [ "$__bbq_pid" != "0" ] && [ "$__bbq_pid" != "1" ]; do',
    '    __bbq_value=""',
    '    if [ -r "/proc/$__bbq_pid/environ" ]; then',
    '      __bbq_value=$(tr "\\000" "\\n" < "/proc/$__bbq_pid/environ" 2>/dev/null | sed -n "s/^${__bbq_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__bbq_value" ]; then',
    '      __bbq_value=$(ps eww -p "$__bbq_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__bbq_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__bbq_value" ]; then',
    '      printf "%s\\n" "$__bbq_value"',
    '      return 0',
    '    fi',
    '    __bbq_pid=$(ps -o ppid= -p "$__bbq_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__bbq_fill_from_ancestor() {',
    '  __bbq_name="$1"',
    '  case "$__bbq_name" in',
    '    BBQ_AGENT_HOOK_ENDPOINT) [ -z "${BBQ_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    BBQ_AGENT_HOOK_PORT) [ -z "${BBQ_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    BBQ_AGENT_HOOK_TOKEN) [ -z "${BBQ_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    BBQ_AGENT_HOOK_ENV) [ -z "${BBQ_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    BBQ_AGENT_HOOK_VERSION) [ -z "${BBQ_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    BBQ_PANE_KEY) [ -z "${BBQ_PANE_KEY:-}" ] || return 0 ;;',
    '    BBQ_TAB_ID) [ -z "${BBQ_TAB_ID:-}" ] || return 0 ;;',
    '    BBQ_WORKTREE_ID) [ -z "${BBQ_WORKTREE_ID:-}" ] || return 0 ;;',
    '    BBQ_AGENT_LAUNCH_TOKEN) [ -z "${BBQ_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __bbq_value=$(__bbq_read_ancestor_var "$__bbq_name") || return 0',
    '  [ -n "$__bbq_value" ] && export "$__bbq_name=$__bbq_value"',
    '}',
    '__bbq_endpoint_value() {',
    '  __bbq_endpoint_name="$1"',
    '  __bbq_endpoint_path="$2"',
    '  sed -n "s/^${__bbq_endpoint_name}=//p" "$__bbq_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__bbq_fill_from_endpoint_file() {',
    '  __bbq_endpoint_path="$1"',
    '  [ -r "$__bbq_endpoint_path" ] || return 0',
    '  __bbq_endpoint_port=$(__bbq_endpoint_value BBQ_AGENT_HOOK_PORT "$__bbq_endpoint_path")',
    '  if [ -n "${BBQ_AGENT_HOOK_PORT:-}" ] && [ -n "$__bbq_endpoint_port" ] && [ "$__bbq_endpoint_port" != "$BBQ_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __bbq_endpoint_name in BBQ_AGENT_HOOK_PORT BBQ_AGENT_HOOK_TOKEN BBQ_AGENT_HOOK_ENV BBQ_AGENT_HOOK_VERSION; do',
    '    eval "__bbq_current=\\${$__bbq_endpoint_name:-}"',
    '    [ -z "$__bbq_current" ] || continue',
    '    __bbq_endpoint_value=$(__bbq_endpoint_value "$__bbq_endpoint_name" "$__bbq_endpoint_path")',
    '    [ -n "$__bbq_endpoint_value" ] && export "$__bbq_endpoint_name=$__bbq_endpoint_value"',
    '  done',
    '}',
    '# Why: Command Code sanitizes hook subprocess env. The parent TUI process',
    '# still has Orca pane/hook metadata, so recover it before posting.',
    'for __bbq_name in BBQ_AGENT_HOOK_ENDPOINT BBQ_AGENT_HOOK_PORT BBQ_AGENT_HOOK_TOKEN BBQ_AGENT_HOOK_ENV BBQ_AGENT_HOOK_VERSION BBQ_PANE_KEY BBQ_TAB_ID BBQ_WORKTREE_ID BBQ_AGENT_LAUNCH_TOKEN; do',
    '  __bbq_fill_from_ancestor "$__bbq_name"',
    'done',
    'if [ -n "$BBQ_AGENT_HOOK_ENDPOINT" ] && [ -r "$BBQ_AGENT_HOOK_ENDPOINT" ]; then',
    '  __bbq_fill_from_endpoint_file "$BBQ_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Why: Command Code strips TOKEN-like env vars before invoking hooks. If',
    '# BBQ_AGENT_HOOK_ENDPOINT was not exported into this PTY, recover the',
    '# matching endpoint file by the unstripped loopback port.',
    'if [ -z "$BBQ_AGENT_HOOK_TOKEN" ] && [ -n "$BBQ_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/orca-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/orca/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/orca/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^BBQ_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$BBQ_AGENT_HOOK_PORT" ]; then',
    '      __bbq_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$BBQ_AGENT_HOOK_PORT" ] || [ -z "$BBQ_AGENT_HOOK_TOKEN" ] || [ -z "$BBQ_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Timeout caps best-effort hook posts if the local listener stalls.
    // Why: pipe payload to curl's stdin (`payload@-`) instead of an inline
    // `payload=$VALUE` arg, so tens-of-KB tool output stays off the curl
    // command line (EDR command-line false positives). Wire body is identical.
    'printf \'%s\' "$payload" | curl -sS -X POST "http://127.0.0.1:${BBQ_AGENT_HOOK_PORT}/hook/command-code" \\',
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Bbq-Agent-Hook-Token: ${BBQ_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${BBQ_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${BBQ_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${BBQ_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${BBQ_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${BBQ_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${BBQ_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
